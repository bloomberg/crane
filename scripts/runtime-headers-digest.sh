#!/bin/sh
# Writes theories/RuntimeHeaders.v (a dune rule in theories/dune): a digest
# of Crane's C++ runtime headers, run from the directory holding cpp/ and
# cpp_bde/.  Crane.Extraction requires it, so every file that loads Crane
# depends on the headers' contents: a build system rebuilds a Crane Bake (an
# image the headers' code computed) when a runtime header changes.
set -e
digest=$(find cpp cpp_bde -type f | LC_ALL=C sort | xargs cat | cksum | tr -s ' \t' '_')
cat <<EOV
(** Generated by scripts/runtime-headers-digest.sh: the digest of Crane's C++
    runtime headers (theories/cpp, theories/cpp_bde).  [Crane.Extraction]
    requires it, so every file that loads Crane is rebuilt when a runtime
    header changes, and with it every image [Crane Bake] computed from the
    old headers.  The digest is in the name: a comment would not change
    the compiled file. *)
Definition runtime_headers_$digest : unit := tt.
EOV
