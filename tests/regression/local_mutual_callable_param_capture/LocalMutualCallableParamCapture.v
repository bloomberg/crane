From Crane Require Import Extraction.
From Crane Require Import Mapping.Std Mapping.NatIntStd.

(** A local mutual group generated by reference ([f_impl], [g_impl] and the
    wrappers [f], [g]), whose members take a callable and only [f] reads the
    enclosing [k]: [f_impl] captures by reference, [g_impl] nothing.  The
    wrapper [g] lends [f_impl] to [g_impl] for the call, which the IR check
    (CRANE_CHECK_IR) took for [f_impl] escaping, since [g_impl], reading
    nothing, was not among the members it lets partners be lent to. *)

Module LocalMutualCallableParamCapture.

  Definition run (k : nat) (n : nat) : nat :=
    (fix f (h : nat -> nat) (n : nat) : nat :=
      match n with
      | O => h 0
      | S m => g h m + k
      end
    with g (h : nat -> nat) (n : nat) : nat :=
      match n with
      | O => h 1
      | S m => f h m
      end
    for f) (fun x => x + 3) n.

End LocalMutualCallableParamCapture.

Crane Extraction "local_mutual_callable_param_capture" LocalMutualCallableParamCapture.
