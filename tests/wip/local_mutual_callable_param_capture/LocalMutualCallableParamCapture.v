From Crane Require Import Extraction.
From Crane Require Import Mapping.Std Mapping.NatIntStd.

(** A local mutual group generated by reference ([f_impl], [g_impl] and the
    wrappers [f], [g]), whose members take a callable and [f] reads the
    enclosing [k].  The IR check (CRANE_CHECK_IR) reports [f_impl] as
    reading its scope by reference and escaping it, so extraction fails.
    Generated with the check off, the C++ compiles and gives the right
    answers: nothing visibly escapes [run].  [f] passing [g] a closure
    instead of forwarding [h] trips it alike; a group that captures nothing
    ([local_mutual_partner_type_arg]) is not checked. *)

Module LocalMutualCallableParamCapture.

  Definition run (k : nat) (n : nat) : nat :=
    (fix f (h : nat -> nat) (n : nat) : nat :=
      match n with
      | O => h 0
      | S m => g h m + k
      end
    with g (h : nat -> nat) (n : nat) : nat :=
      match n with
      | O => h 1
      | S m => f h m
      end
    for f) (fun x => x + 3) n.

End LocalMutualCallableParamCapture.

Crane Extraction "local_mutual_callable_param_capture" LocalMutualCallableParamCapture.
